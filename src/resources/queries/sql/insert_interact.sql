    THEN SUM( CASE WHEN BUY_SELL_CODE='001' THEN TXN_AMT_TWD ELSE 0 END ) - SUM( CASE WHEN BUY_SELL_CODE='002' THEN TXN_AMT_TWD ELSE 0 END ) ELSE NULL END AS ALL_PROD_NET_AMT_DAY,
